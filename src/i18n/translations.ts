export const defaultLanguage: 'en' | 'hi' = 'en';

export function getTranslation(lang: 'en' | 'hi', key: string): string {
  const keys = key.split('.');
  let value: any = translations[lang];
  for (const k of keys) {
    value = value?.[k];
    if (value === undefined) break;
  }
  return value || key;
}
